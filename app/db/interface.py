from abc import ABC, abstractmethod
from app.models import Region, Operator, NumberRange, Employee


class NumberingRepository(ABC):
    """Контракт доступа к данным. UI, сервисы и тесты зависят только от него."""

    @abstractmethod
    def add_region(self, region: Region) -> int: ...
    @abstractmethod
    def list_regions(self) -> list[Region]: ...

    @abstractmethod
    def add_operator(self, operator: Operator) -> int: ...
    @abstractmethod
    def list_operators(self) -> list[Operator]: ...

    @abstractmethod
    def add_range(self, number_range: NumberRange) -> int: ...
    @abstractmethod
    def list_ranges(self) -> list[NumberRange]: ...
    @abstractmethod
    def delete_range(self, range_id: int) -> None: ...
    @abstractmethod
    def find_range(self, def_code: str, number: str) -> NumberRange | None: ...

    @abstractmethod
    def add_employee(self, employee: Employee) -> int: ...
    @abstractmethod
    def list_employees(self) -> list[Employee]: ...
    @abstractmethod
    def get_employee_by_username(self, username: str) -> Employee | None: ...
    @abstractmethod
    def update_employee_password(self, employee_id: int, password_hash: str, salt: str) -> None: ...
    @abstractmethod
    def set_employee_active(self, employee_id: int, active: bool) -> None: ...
